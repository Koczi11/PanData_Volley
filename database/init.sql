-- 3.1. Enforce tenant scoping rule on users:
--      super_admin -> club_id IS NULL
--      all club roles -> club_id IS NOT NULL
CREATE OR REPLACE FUNCTION fn_users_role_club_scope()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_role_code VARCHAR(32);
BEGIN
    SELECT code
      INTO v_role_code
      FROM roles
     WHERE id = NEW.role_id;

    IF v_role_code IS NULL THEN
        RAISE EXCEPTION 'Invalid role_id: %', NEW.role_id
            USING ERRCODE = 'foreign_key_violation';
    END IF;

    IF v_role_code = 'super_admin' AND NEW.club_id IS NOT NULL THEN
        RAISE EXCEPTION 'Role super_admin must have club_id IS NULL (got club_id=%)', NEW.club_id
            USING ERRCODE = 'check_violation';
    END IF;

    IF v_role_code <> 'super_admin' AND NEW.club_id IS NULL THEN
        RAISE EXCEPTION 'Club role "%" requires a non-null club_id', v_role_code
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_users_role_club_scope ON users;
CREATE TRIGGER trg_users_role_club_scope
    BEFORE INSERT OR UPDATE OF role_id, club_id
    ON users
    FOR EACH ROW
    EXECUTE FUNCTION fn_users_role_club_scope();

-- 3.2. Automatically recalculate club_sets_won and opponent_sets_won in matches
--      whenever match_sets rows are inserted, updated, or deleted.
CREATE OR REPLACE FUNCTION fn_match_sets_recalculate_score()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_match_id INTEGER;
BEGIN
    v_match_id := COALESCE(NEW.match_id, OLD.match_id);

    UPDATE matches m
       SET club_sets_won = COALESCE((
               SELECT COUNT(*)
                 FROM match_sets ms
                WHERE ms.match_id = v_match_id
                  AND ms.club_points > ms.opponent_points
           ), 0),
           opponent_sets_won = COALESCE((
               SELECT COUNT(*)
                 FROM match_sets ms
                WHERE ms.match_id = v_match_id
                  AND ms.opponent_points > ms.club_points
           ), 0)
     WHERE m.id = v_match_id;

    -- Also recalculate the previous match if a set was moved between matches
    IF TG_OP = 'UPDATE' AND OLD.match_id IS DISTINCT FROM NEW.match_id THEN
        UPDATE matches m
           SET club_sets_won = COALESCE((
                   SELECT COUNT(*)
                     FROM match_sets ms
                    WHERE ms.match_id = OLD.match_id
                      AND ms.club_points > ms.opponent_points
               ), 0),
               opponent_sets_won = COALESCE((
                   SELECT COUNT(*)
                     FROM match_sets ms
                    WHERE ms.match_id = OLD.match_id
                      AND ms.opponent_points > ms.club_points
               ), 0)
         WHERE m.id = OLD.match_id;
    END IF;

    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_match_sets_recalculate_score ON match_sets;
CREATE TRIGGER trg_match_sets_recalculate_score
    AFTER INSERT OR UPDATE OR DELETE
    ON match_sets
    FOR EACH ROW
    EXECUTE FUNCTION fn_match_sets_recalculate_score();

-- 3.3. Automatically maintain updated_at timestamp on mutable core tables
CREATE OR REPLACE FUNCTION fn_set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_set_updated_at ON clubs;

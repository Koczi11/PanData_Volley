-- 4.1. Super-admin overview per club (user breakdown by role, matches, videos, activity)
CREATE OR REPLACE VIEW v_club_overview AS
WITH users_agg AS (
    SELECT
        u.club_id,
        COUNT(*)::INTEGER AS users_total,
        COUNT(*) FILTER (WHERE r.code = 'admin')::INTEGER AS admins_count,
        COUNT(*) FILTER (WHERE r.code = 'coach')::INTEGER AS coaches_count,
        COUNT(*) FILTER (WHERE r.code = 'analyst')::INTEGER AS analysts_count,
        COUNT(*) FILTER (WHERE r.code = 'player')::INTEGER AS players_count,
        MAX(u.last_login_at) AS last_login_at
    FROM users u
    JOIN roles r ON r.id = u.role_id
    WHERE u.club_id IS NOT NULL
    GROUP BY u.club_id
),
matches_agg AS (
    SELECT
        m.club_id,
        COUNT(*)::INTEGER AS matches_count,
        MAX(m.updated_at) AS last_match_updated_at
    FROM matches m
    GROUP BY m.club_id
),
videos_agg AS (
    SELECT
        m.club_id,
        COUNT(mv.id)::INTEGER AS videos_count,
        MAX(mv.created_at) AS last_video_created_at
    FROM match_videos mv
    JOIN matches m ON m.id = mv.match_id
    GROUP BY m.club_id
),
audit_agg AS (
    SELECT
        al.club_id,
        MAX(al.created_at) AS last_audit_at
    FROM audit_logs al
    WHERE al.club_id IS NOT NULL
    GROUP BY al.club_id
)
SELECT
    c.id AS club_id,
    c.name AS club_name,
    c.short_name,
    c.slug,
    c.city,
    c.league,
    c.is_active,
    COALESCE(ua.users_total, 0) AS users_total,
    COALESCE(ua.admins_count, 0) AS admins_count,
    COALESCE(ua.coaches_count, 0) AS coaches_count,
    COALESCE(ua.analysts_count, 0) AS analysts_count,
    COALESCE(ua.players_count, 0) AS players_count,
    COALESCE(ma.matches_count, 0) AS matches_count,
    COALESCE(va.videos_count, 0) AS videos_count,
    GREATEST(
        c.updated_at,
        ua.last_login_at,
        ma.last_match_updated_at,
        va.last_video_created_at,
        aa.last_audit_at
    ) AS last_activity_at
FROM clubs c
LEFT JOIN users_agg ua ON ua.club_id = c.id
LEFT JOIN matches_agg ma ON ma.club_id = c.id
LEFT JOIN videos_agg va ON va.club_id = c.id
LEFT JOIN audit_agg aa ON aa.club_id = c.id;

-- 4.2. Aggregated seasonal player statistics
CREATE OR REPLACE VIEW v_player_season_stats AS
SELECT
    u.id AS player_user_id,
    u.club_id,
    c.name AS club_name,
    m.season,
    u.first_name,
    u.last_name,
    (u.first_name || ' ' || u.last_name) AS full_name,
    pp.jersey_number,
    pp.position,
    pp.status AS player_status,
    COUNT(DISTINCT pms.match_id)::INTEGER AS matches_played,
    COALESCE(SUM(pms.sets_played), 0)::INTEGER AS sets_played,
    COALESCE(SUM(pms.points_total), 0)::INTEGER AS points_total,
    COALESCE(SUM(pms.serves_total), 0)::INTEGER AS serves_total,
    COALESCE(SUM(pms.serve_aces), 0)::INTEGER AS serve_aces,
    COALESCE(SUM(pms.serve_errors), 0)::INTEGER AS serve_errors,
    COALESCE(SUM(pms.receptions_total), 0)::INTEGER AS receptions_total,
    COALESCE(SUM(pms.reception_positive), 0)::INTEGER AS reception_positive,
    COALESCE(SUM(pms.reception_perfect), 0)::INTEGER AS reception_perfect,
    COALESCE(SUM(pms.reception_errors), 0)::INTEGER AS reception_errors,
    CASE
        WHEN COALESCE(SUM(pms.receptions_total), 0) > 0
            THEN ROUND((SUM(pms.reception_positive)::NUMERIC / SUM(pms.receptions_total)) * 100, 2)
        ELSE 0.00
    END AS positive_reception_pct,
    CASE
        WHEN COALESCE(SUM(pms.receptions_total), 0) > 0
            THEN ROUND((SUM(pms.reception_perfect)::NUMERIC / SUM(pms.receptions_total)) * 100, 2)
        ELSE 0.00
    END AS perfect_reception_pct,
    COALESCE(SUM(pms.attacks_total), 0)::INTEGER AS attacks_total,
    COALESCE(SUM(pms.attack_kills), 0)::INTEGER AS attack_kills,
    COALESCE(SUM(pms.attack_errors), 0)::INTEGER AS attack_errors,
    COALESCE(SUM(pms.attack_blocked), 0)::INTEGER AS attack_blocked,
    CASE
        WHEN COALESCE(SUM(pms.attacks_total), 0) > 0
            THEN ROUND((SUM(pms.attack_kills)::NUMERIC / SUM(pms.attacks_total)) * 100, 2)
        ELSE 0.00
    END AS attack_efficiency_pct,
    CASE
        WHEN COALESCE(SUM(pms.attacks_total), 0) > 0
            THEN ROUND(
                ((SUM(pms.attack_kills) - SUM(pms.attack_errors) - SUM(pms.attack_blocked))::NUMERIC
                 / SUM(pms.attacks_total)) * 100,
                2
            )
        ELSE 0.00
    END AS attack_net_efficiency_pct,
    COALESCE(SUM(pms.blocks_kill), 0)::INTEGER AS blocks_kill,
    COALESCE(SUM(pms.digs), 0)::INTEGER AS digs
FROM player_match_stats pms
JOIN matches m ON m.id = pms.match_id
JOIN users u ON u.id = pms.player_user_id
JOIN player_profiles pp ON pp.user_id = u.id
JOIN clubs c ON c.id = u.club_id
GROUP BY
    u.id,
    u.club_id,
    c.name,
    m.season,
    u.first_name,
    u.last_name,
    pp.jersey_number,
    pp.position,
    pp.status;


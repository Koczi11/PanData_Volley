        CONSTRAINT chk_player_profiles_height CHECK (height_cm BETWEEN 140 AND 235),
    reach_attack_cm SMALLINT
        CONSTRAINT chk_player_profiles_reach_attack CHECK (reach_attack_cm BETWEEN 200 AND 400),
    reach_block_cm  SMALLINT
        CONSTRAINT chk_player_profiles_reach_block CHECK (reach_block_cm BETWEEN 190 AND 380),

-- 1.1. Roles dictionary (global roles: super_admin + club-scoped roles)
CREATE TABLE IF NOT EXISTS roles (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(32) NOT NULL UNIQUE,
    name        VARCHAR(64) NOT NULL,
    description VARCHAR(255)
);

-- 1.2. Volleyball clubs (tenants). created_by FK is added after users exists.
CREATE TABLE IF NOT EXISTS clubs (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(150) NOT NULL,
    short_name  VARCHAR(32) NOT NULL,
    slug        VARCHAR(100) NOT NULL UNIQUE
        CONSTRAINT chk_clubs_slug_format CHECK (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
    city        VARCHAR(100) NOT NULL,
    league      VARCHAR(100),
    logo_path   VARCHAR(255),
    is_active   BOOLEAN NOT NULL DEFAULT TRUE,
    created_by  INTEGER,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 1.3. Application users
CREATE TABLE IF NOT EXISTS users (
    id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id          INTEGER NOT NULL REFERENCES roles(id) ON DELETE RESTRICT,
    club_id          INTEGER REFERENCES clubs(id) ON DELETE RESTRICT,
    email            VARCHAR(255) NOT NULL UNIQUE
        CONSTRAINT chk_users_email_format CHECK (email = LOWER(email) AND POSITION('@' IN email) > 1),
    password_hash    VARCHAR(255) NOT NULL,
    first_name       VARCHAR(80) NOT NULL,
    last_name        VARCHAR(80) NOT NULL,
    avatar_path      VARCHAR(255),
    preferred_locale VARCHAR(10) NOT NULL DEFAULT 'en'
        CONSTRAINT chk_users_preferred_locale CHECK (preferred_locale IN ('en', 'pl')),
    is_active        BOOLEAN NOT NULL DEFAULT TRUE,
    last_login_at    TIMESTAMPTZ,
    created_by       INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Resolve circular reference clubs.created_by -> users.id idempotently
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'fk_clubs_created_by'
          AND conrelid = 'clubs'::regclass
    ) THEN
        ALTER TABLE clubs
            ADD CONSTRAINT fk_clubs_created_by
            FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL;
    END IF;
END;
$$;

-- 1.4. Athletic profiles for players (1:0..1 extension of users)
CREATE TABLE IF NOT EXISTS player_profiles (
    user_id         INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    jersey_number   SMALLINT
        CONSTRAINT chk_player_profiles_jersey_number CHECK (jersey_number BETWEEN 1 AND 99),
    position        VARCHAR(32) NOT NULL

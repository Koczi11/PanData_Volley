-- 1.6. Volleyball matches belonging to a club
CREATE TABLE IF NOT EXISTS matches (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id           INTEGER NOT NULL REFERENCES clubs(id) ON DELETE RESTRICT,
    opponent_name     VARCHAR(150) NOT NULL,
    competition       VARCHAR(120) NOT NULL,
    season            VARCHAR(20) NOT NULL,
    match_date        TIMESTAMPTZ NOT NULL,
    location          VARCHAR(150),
    is_home           BOOLEAN NOT NULL DEFAULT TRUE,
    status            VARCHAR(24) NOT NULL DEFAULT 'scheduled'
        CONSTRAINT chk_matches_status CHECK (status IN ('scheduled', 'live', 'finished', 'cancelled')),
    club_sets_won     SMALLINT NOT NULL DEFAULT 0
        CONSTRAINT chk_matches_club_sets_won CHECK (club_sets_won BETWEEN 0 AND 5),
    opponent_sets_won SMALLINT NOT NULL DEFAULT 0
